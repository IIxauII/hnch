#!/usr/bin/env bash
# Provisions a git worktree for parallel hnch dev:
#   - assigns unique CLIENT_PORT/RELAY_PORT via lowest-unused offset
#   - writes .env.local at worktree root (overwrites — bootstrap is source of truth)
#   - runs pnpm install
#
# ALWAYS regenerates .env.local. Manual edits are lost. Rerun is safe.
#
# Convention: RELAY_PORT = 1234 + (CLIENT_PORT - 4200). Client derives from
# window.location.port — must match.
#
# Compatible with macOS stock bash 3.2 (no flock, no advanced array features).
#
# Usage: from inside the worktree dir, run `bash scripts/worktree-bootstrap.sh`
# or via the wrapper `pnpm worktree:bootstrap`.

set -eo pipefail

# --- Locking (mkdir-based; portable, works on macOS without `flock`) -------
GIT_COMMON_DIR="$(git rev-parse --git-common-dir)"
LOCK_DIR="${GIT_COMMON_DIR}/worktree-bootstrap.lock"
LOCK_TIMEOUT=30  # seconds

acquire_lock() {
  local elapsed=0
  while ! mkdir "$LOCK_DIR" 2>/dev/null; do
    if [ "$elapsed" -ge "$LOCK_TIMEOUT" ]; then
      echo "✗ Could not acquire bootstrap lock after ${LOCK_TIMEOUT}s." >&2
      echo "  Stale lock? Remove with: rmdir \"$LOCK_DIR\"" >&2
      exit 1
    fi
    sleep 1
    elapsed=$((elapsed + 1))
  done
  # Release lock on any exit path.
  trap 'rmdir "$LOCK_DIR" 2>/dev/null || true' EXIT
}

acquire_lock

WORKTREE_PATH="$(pwd)"
WORKTREE_NAME="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo unknown)"

echo "→ Bootstrapping worktree: $WORKTREE_NAME at $WORKTREE_PATH"

# --- Step 1: prune stale worktree refs ------------------------------------
# Cleans entries whose dirs were `rm -rf`'d without `git worktree remove`.
git worktree prune

# --- Step 2: enumerate existing worktrees + collect used ports ------------
# Bash 3.2-safe: use newline-delimited strings, not arrays-of-args.
USED_CLIENT_PORTS=""
USED_RELAY_PORTS=""

while IFS= read -r line; do
  case "$line" in
    "worktree "*)
      wt_path="${line#worktree }"
      env_file="$wt_path/.env.local"
      if [ -f "$env_file" ]; then
        cp=$(grep -E '^CLIENT_PORT=' "$env_file" | tail -n1 | cut -d= -f2 || true)
        rp=$(grep -E '^RELAY_PORT=' "$env_file" | tail -n1 | cut -d= -f2 || true)
        if [ -n "$cp" ]; then USED_CLIENT_PORTS="$USED_CLIENT_PORTS $cp"; fi
        if [ -n "$rp" ]; then USED_RELAY_PORTS="$USED_RELAY_PORTS $rp"; fi
      fi
      ;;
  esac
done < <(git worktree list --porcelain)

# --- Step 3: pick lowest unused offset N ∈ {100, 200, ...} ---------------
# Both 4200+N and 1234+N must be free in used-set AND not currently bound.
# N=0 is reserved for the main worktree (which runs without .env.local).

is_used() {
  # $1 = port to check, $2 = space-delimited list
  local port="$1"
  local list="$2"
  case " $list " in
    *" $port "*) return 0 ;;
    *)           return 1 ;;
  esac
}

is_bound() {
  local port="$1"
  if command -v nc >/dev/null 2>&1; then
    nc -z localhost "$port" >/dev/null 2>&1
  elif command -v lsof >/dev/null 2>&1; then
    lsof -i ":$port" -sTCP:LISTEN >/dev/null 2>&1
  else
    return 1
  fi
}

OFFSET=100
MAX_OFFSET=9000
while [ "$OFFSET" -le "$MAX_OFFSET" ]; do
  cp=$((4200 + OFFSET))
  rp=$((1234 + OFFSET))
  if is_used "$cp" "$USED_CLIENT_PORTS"; then
    OFFSET=$((OFFSET + 100)); continue
  fi
  if is_used "$rp" "$USED_RELAY_PORTS"; then
    OFFSET=$((OFFSET + 100)); continue
  fi
  if is_bound "$cp"; then
    OFFSET=$((OFFSET + 100)); continue
  fi
  if is_bound "$rp"; then
    OFFSET=$((OFFSET + 100)); continue
  fi
  break
done

if [ "$OFFSET" -gt "$MAX_OFFSET" ]; then
  echo "✗ No free port offset found between 100 and $MAX_OFFSET" >&2
  exit 1
fi

CLIENT_PORT=$((4200 + OFFSET))
RELAY_PORT=$((1234 + OFFSET))

echo "→ Assigned offset $OFFSET → CLIENT_PORT=$CLIENT_PORT, RELAY_PORT=$RELAY_PORT"

# --- Step 4: write .env.local (overwrite — source of truth) ---------------
cat > .env.local <<EOF
# Generated by scripts/worktree-bootstrap.sh — do not edit by hand.
# Rerun \`pnpm worktree:bootstrap\` to regenerate.
#
# Convention: RELAY_PORT = 1234 + (CLIENT_PORT - 4200). Client derives from
# window.location.port — keep these in lockstep.
CLIENT_PORT=$CLIENT_PORT
RELAY_PORT=$RELAY_PORT
PORT=$RELAY_PORT
HNCH_RELAY_URL=http://localhost:$RELAY_PORT
PLAYWRIGHT_BASE_URL=http://localhost:$CLIENT_PORT
EOF

echo "→ Wrote .env.local"

# --- Step 5: pnpm install -------------------------------------------------
echo "→ Running pnpm install..."
pnpm install

echo ""
echo "✓ Worktree bootstrap complete."
echo ""
echo "  Path:        $WORKTREE_PATH"
echo "  Branch:      $WORKTREE_NAME"
echo "  Client port: $CLIENT_PORT"
echo "  Relay port:  $RELAY_PORT"
echo ""
echo "  Next: cd into the worktree and run \`pnpm dev:relay\` + \`pnpm dev:client\`."
